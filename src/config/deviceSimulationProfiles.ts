export function getDeviceSimulationProfile(
  deviceId: string | null | undefined,
  fallbackRecord?: DeviceRecord | null,
): DeviceSimulationProfile {
  if (deviceId && DEVICE_SIMULATION_PROFILES[deviceId]) {
    return DEVICE_SIMULATION_PROFILES[deviceId];
  }
  const kind = fallbackRecord?.kind?.toLowerCase() ?? '';
  if (kind.includes('helicopter')) {
    return DEVICE_SIMULATION_PROFILES.ingenuity_helicopter;
  }
  if (kind.includes('orbiter') || kind.includes('spacecraft') || kind.includes('telescope')) {
    return DEVICE_SIMULATION_PROFILES.mro_orbiter;
  }
  if (fallbackRecord?.bodyId === 'moon') {
    return DEVICE_SIMULATION_PROFILES.apollo_lrv;
  }
  return DEVICE_SIMULATION_PROFILES.perseverance_rover;
}

export function isSurfaceSimulationDevice(profile: DeviceSimulationProfile): boolean {
  return profile.mobilityKind !== 'orbital';
}

export function hasRealMobility(profile: DeviceSimulationProfile): boolean {
  return profile.capabilities.supportsRealMobility || profile.capabilities.supportsFlight;
}
